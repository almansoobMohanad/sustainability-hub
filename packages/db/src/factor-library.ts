import { existsSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { eq, sql } from 'drizzle-orm'
import type { Database } from './client'
import { emissionFactors, emissionSources, factorLibraries, factorSets } from './schema'

/*
  Loads the emission factor library (seed/uk-ghg, generated by
  scripts/import-uk-factors.mjs) into the database. The API calls this on
  every startup, right after the migrations:
  - first start: loads every year (about 19,000 factors, a second or two)
  - later starts: compares the hashes in manifest.json with what's loaded and
    does nothing, unless a year was added or corrected in the seed files
  So the desktop installer, Docker and the cloud all get the factors with no
  setup step, and shipping a new year is just committing new seed files.

  Factor rows of a year are replaced when that year is reloaded, so nothing
  may reference emission_factors.id: entries store the source, unit, year and
  the value they were calculated with instead.
*/

export const UK_FACTOR_LIBRARY = 'uk-ghg'

/*
  Bump when the way sources are stored changes (e.g. how `name` is built), so
  every database reloads its sources once even though the seed files didn't change.
*/
const SOURCES_FORMAT = 2

/**
 * "Liquid fuels · Diesel (average biofuel blend)". With only one level below
 * the category, the category is included ("Hotel stay · Malaysia", not just
 * "Malaysia"); with none, the category alone ("Water supply").
 */
function sourceName(category: string, path: string[]) {
  return (path.length >= 2 ? path : [category, ...path]).join(' · ')
}

type Manifest = {
  format: 1
  publisher: string
  title: string
  licence: string
  licenceUrl: string
  sourcesSha256: string
  sets: { year: number; version: string; file: string; factorCount: number; contentSha256: string; sourceUrl: string }[]
}
type SeedSource = { ref: string; key: string; scope: number; category: string; path: string[] }
type SeedFactor = [ref: string, unit: string, kgCo2ePerUnit: number]

const here = dirname(fileURLToPath(import.meta.url))

/**
 * Where the seed files are:
 * - running from source (development): packages/db/seed
 * - running the bundled API (apps/api/dist): copied next to the bundle at build time
 */
function findSeedFolder() {
  const candidates = [join(here, '../seed', UK_FACTOR_LIBRARY), join(here, 'seed', UK_FACTOR_LIBRARY)]
  return candidates.find((dir) => existsSync(join(dir, 'manifest.json')))
}

const readJson = <T>(folder: string, file: string) => JSON.parse(readFileSync(join(folder, file), 'utf8')) as T

/** Multi-row inserts, in chunks that stay well under Postgres's 65,535 parameter limit */
function chunks<T>(items: T[], size: number) {
  const result: T[][] = []
  for (let i = 0; i < items.length; i += size) result.push(items.slice(i, i + size))
  return result
}

export type FactorLibraryResult =
  | { loaded: false; reason: string }
  | { loaded: true; years: number[]; reloadedYears: number[]; sourcesReloaded: boolean }

export async function loadFactorLibrary(db: Database): Promise<FactorLibraryResult> {
  const folder = findSeedFolder()
  if (!folder) return { loaded: false, reason: 'seed files not found' }
  const manifest = readJson<Manifest>(folder, 'manifest.json')
  const years = manifest.sets.map((set) => set.year)

  return db.transaction(async (tx) => {
    // Several API instances can start at once (cloud); one loads, the others wait and then find nothing to do
    await tx.execute(sql`select pg_advisory_xact_lock(hashtext('hub:factor-library'))`)

    const [library] = await tx
      .select({ sourcesSha256: factorLibraries.sourcesSha256 })
      .from(factorLibraries)
      .where(eq(factorLibraries.code, UK_FACTOR_LIBRARY))
    const loadedSets = await tx
      .select({ year: factorSets.year, contentSha256: factorSets.contentSha256 })
      .from(factorSets)
      .where(eq(factorSets.libraryCode, UK_FACTOR_LIBRARY))
    const loadedHash = new Map(loadedSets.map((set) => [set.year, set.contentSha256]))

    const sourcesVersion = `${manifest.sourcesSha256}/format-${SOURCES_FORMAT}`
    const sourcesReloaded = library?.sourcesSha256 !== sourcesVersion
    const setsToLoad = manifest.sets.filter((set) => loadedHash.get(set.year) !== set.contentSha256)
    if (!sourcesReloaded && setsToLoad.length === 0) {
      return { loaded: true, years, reloadedYears: [], sourcesReloaded: false }
    }

    const libraryRow = {
      code: UK_FACTOR_LIBRARY,
      title: manifest.title,
      publisher: manifest.publisher,
      licence: manifest.licence,
      licenceUrl: manifest.licenceUrl,
      sourcesSha256: sourcesVersion,
      updatedAt: new Date(),
    }
    await tx.insert(factorLibraries).values(libraryRow).onConflictDoUpdate({ target: factorLibraries.code, set: libraryRow })

    const sources = readJson<SeedSource[]>(folder, 'sources.json')
    if (sourcesReloaded) {
      // Upsert by key: existing sources keep their id (companies point at them).
      // A source dropped from the seed stays in the table, just without new factors.
      const rows = sources.map((source, index) => ({
        libraryCode: UK_FACTOR_LIBRARY,
        key: source.key,
        scope: source.scope,
        category: source.category,
        path: source.path,
        name: sourceName(source.category, source.path),
        sortOrder: index,
      }))
      for (const chunk of chunks(rows, 1000)) {
        await tx
          .insert(emissionSources)
          .values(chunk)
          .onConflictDoUpdate({
            target: [emissionSources.libraryCode, emissionSources.key],
            set: {
              scope: sql`excluded.scope`,
              category: sql`excluded.category`,
              path: sql`excluded.path`,
              name: sql`excluded.name`,
              sortOrder: sql`excluded.sort_order`,
            },
          })
      }
    }

    // ref (short id used in the seed files) -> database id
    const idByKey = new Map(
      (
        await tx
          .select({ id: emissionSources.id, key: emissionSources.key })
          .from(emissionSources)
          .where(eq(emissionSources.libraryCode, UK_FACTOR_LIBRARY))
      ).map((row) => [row.key, row.id]),
    )
    const idByRef = new Map(sources.map((source) => [source.ref, idByKey.get(source.key)]))

    for (const set of setsToLoad) {
      const setRow = {
        libraryCode: UK_FACTOR_LIBRARY,
        year: set.year,
        version: set.version,
        sourceUrl: set.sourceUrl,
        contentSha256: set.contentSha256,
        factorCount: set.factorCount,
        loadedAt: new Date(),
      }
      const [{ id: factorSetId }] = await tx
        .insert(factorSets)
        .values(setRow)
        .onConflictDoUpdate({ target: [factorSets.libraryCode, factorSets.year], set: setRow })
        .returning({ id: factorSets.id })

      await tx.delete(emissionFactors).where(eq(emissionFactors.factorSetId, factorSetId))
      const rows = readJson<SeedFactor[]>(folder, set.file).map(([ref, unit, kgCo2ePerUnit]) => {
        const sourceId = idByRef.get(ref)
        if (!sourceId) throw new Error(`Factor library: ${set.file} refers to unknown source ${ref}`)
        return { factorSetId, sourceId, unit, kgCo2ePerUnit }
      })
      for (const chunk of chunks(rows, 2000)) await tx.insert(emissionFactors).values(chunk)
    }

    return { loaded: true, years, reloadedYears: setsToLoad.map((set) => set.year), sourcesReloaded }
  })
}
