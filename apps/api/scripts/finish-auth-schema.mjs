// Runs after Better Auth's CLI regenerates packages/db/src/schema/auth.ts.
// Things the CLI can't express, applied every time so they survive regeneration:
// - timestamps become "timestamp with time zone" (always the exact moment,
//   whatever time zone the server runs in)
// - sessions.active_organization_id: a real uuid reference to organizations,
//   cleared automatically when that company is deleted (the CLI makes it plain text)
// - members: unique (organization_id, user_id), so nobody can be a member of the
//   same company twice, even if two requests race past Better Auth's own check
// - a header saying the file is generated
import { readFileSync, writeFileSync } from 'node:fs'

const file = new URL('../../../packages/db/src/schema/auth.ts', import.meta.url)
const HEADER = `// GENERATED by Better Auth's CLI: run \`pnpm --filter @hub/api auth:schema\`, don't edit by hand.
// (apps/api/scripts/finish-auth-schema.mjs then adjusts it: time zones, references, unique members.)
`

let source = readFileSync(file, 'utf8')

/** Replace once, and fail loudly if the CLI's output changed shape. */
function replaceOnce(search, replacement, what) {
  if (source.includes(replacement)) return // already applied
  if (!source.includes(search)) throw new Error(`finish-auth-schema: couldn't find ${what}; update this script.`)
  source = source.replace(search, replacement)
}

source = source.replace(/timestamp\("([a-z_]+)"\)/g, 'timestamp("$1", { withTimezone: true })')

if (source.includes('export const organizations')) {
  replaceOnce(
    'activeOrganizationId: text("active_organization_id"),',
    'activeOrganizationId: uuid("active_organization_id").references(() => organizations.id, { onDelete: "set null" }),',
    'sessions.activeOrganizationId',
  )
  replaceOnce(
    'index("members_userId_idx").on(table.userId),',
    'index("members_userId_idx").on(table.userId),\n    uniqueIndex("members_organization_user_unique").on(table.organizationId, table.userId),',
    'the members indexes',
  )
  replaceOnce('  index,\n} from "drizzle-orm/pg-core";', '  index,\n  uniqueIndex,\n} from "drizzle-orm/pg-core";', 'the pg-core import')
}

if (!source.startsWith(HEADER)) source = HEADER + source.replace(/^\/\/ GENERATED[^\n]*\n\/\/[^\n]*\n/, '')
writeFileSync(file, source)
console.log('Auth schema: time zones, active company reference and unique memberships applied.')
