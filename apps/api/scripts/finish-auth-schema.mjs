// Runs after Better Auth's CLI regenerates packages/db/src/schema/auth.ts:
// - timestamps become "timestamp with time zone" (always the exact moment,
//   whatever time zone the server runs in)
// - adds a header saying the file is generated
import { readFileSync, writeFileSync } from 'node:fs'

const file = new URL('../../../packages/db/src/schema/auth.ts', import.meta.url)
const HEADER = `// GENERATED by Better Auth's CLI: run \`pnpm --filter @hub/api auth:schema\`, don't edit by hand.
// (apps/api/scripts/finish-auth-schema.mjs then switches timestamps to "with time zone".)
`

let source = readFileSync(file, 'utf8')
source = source.replace(/timestamp\("([a-z_]+)"\)/g, 'timestamp("$1", { withTimezone: true })')
if (!source.startsWith(HEADER)) source = HEADER + source
writeFileSync(file, source)
console.log('Auth schema: timestamps use time zones.')
